"""Read-only scheme catalogue for citizens: active central schemes and Punjab's own,
exactly as the assistant sees them. Nothing here is generated by the model."""

from typing import Any

from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm import selectinload

from app.core.errors import APIError
from app.models.enums import SchemeReviewStatus
from app.models.scheme import Scheme
from app.schemas.grievance import NamedOut
from app.schemas.scheme_catalog import SchemeInfoOut, SchemeSummaryOut
from app.services.scheme_search import active_schemes


def _summary(s: Scheme) -> dict[str, Any]:
    return {
        "slug": s.slug,
        "name": s.name,
        "short_name": s.short_name,
        "name_pa": s.name_pa,
        "level": s.level,
        "department": NamedOut.model_validate(s.department) if s.department else None,
        "description": s.description,
        "benefits": s.benefits,
        "category_tags": [str(t) for t in s.category_tags or []],
        "official_url": s.official_url,
    }


async def list_schemes(db: AsyncSession) -> list[SchemeSummaryOut]:
    rows = await db.scalars(
        active_schemes().options(selectinload(Scheme.department)).order_by(Scheme.name)
    )
    return [SchemeSummaryOut(**_summary(s)) for s in rows]


async def get_scheme(db: AsyncSession, slug: str) -> SchemeInfoOut:
    scheme = await db.scalar(
        active_schemes()
        .where(Scheme.slug == slug)
        .options(selectinload(Scheme.department), selectinload(Scheme.conditions))
    )
    if scheme is None:
        raise APIError(["resource.scheme.not_found"], 404)

    required: list[str] = []
    groups: dict[str, list[str]] = {}
    for c in scheme.conditions:
        if c.group_key:
            groups.setdefault(c.group_key, []).append(c.description)
        else:
            required.append(c.description)
    verified = scheme.review_status == SchemeReviewStatus.verified.value
    return SchemeInfoOut(
        **_summary(scheme),
        administering_body=scheme.administering_body,
        conditions=required,
        any_of_conditions=list(groups.values()),
        required_documents=list(scheme.required_documents or []),
        application_steps=list(scheme.application_steps or []),
        application_mode=scheme.application_mode,
        deadline_info=scheme.deadline_info,
        contact=scheme.contact,
        source_name=scheme.source_name,
        source_url=scheme.source_url,
        checked_on=scheme.last_verified_on if verified else None,
    )
